package me.vangoo.mysteries.client.render

import net.minecraft.client.gui.GuiGraphicsExtractor

/** Native GUI pixels keep every symbol on the same grid, without resampling a texture. */
object BookGlyphs {
    val patterns = mapOf(
        "status" to "...###.../..#...#../..#...#../...###.../........./..#####../.#.....#./.#.....#./.#######.",
        "library" to ".###.###./#...#...#/#.#.#.#.#/#...#...#/#.#.#.#.#/#...#...#/#.#.#.#.#/#...#...#/.###.###.",
        "keys" to "........./#########/#.......#/#.#.#.#.#/#.......#/#.#.#.#.#/#..###..#/#########/.........",
        "groups" to "..##.##../.#..#..#./.#..#..#./..##.##../........./.###.###./#...#...#/#...#...#/#########",
        "search" to "..###..../.#...#.../#.....#../#.....#../#.....#../.#...#.../..###.#../.......#./........#",
        "active" to ".....###./....###../...###.../..######./.######../....##.../...##..../..##...../.##......",
        "toggle" to "........./........./.#######./#....##.#/#....##.#/#....##.#/.#######./........./.........",
        "passive" to ".#######./.#.....#./.#.....#./.#.....#./.#.....#./..#...#../..#...#../...#.#.../....#....",
        "cooldown" to "...###.../.##...##./.#..#..#./#...#...#/#...###.#/#.......#/.#.....#./.##...##./...###...",
        "sustain" to "...###.../.##...##./.#.....#./#.......#/#.......#/#.......#/.#.....#./.##...##./...###...",
        "lock" to "..#####../.#.....#./.#.....#./.#######./.#.....#./.#..#..#./.#..#..#./.#.....#./.#######.",
        "check" to "........./........#/.......#./......#../#....#.../.#..#..../..##...../...#...../.........",
        "warn" to "....#..../...#.#.../...#.#.../..#.#.#../..#.#.#../.#..#..#./.#.....#./#...#...#/#########",
        "plus" to "........./....#..../....#..../....#..../.#######./....#..../....#..../....#..../.........",
        "up" to "....#..../...###.../..#.#.#../.#..#..#./....#..../....#..../....#..../....#..../....#....",
        "down" to "....#..../....#..../....#..../....#..../....#..../.#..#..#./..#.#.#../...###.../....#....",
        "cross" to "...###.../.#######./........./..#...#../..#.#.#../..#.#.#../..#.#.#../..#...#../..#####..",
    ).mapValues { (_, rows) -> rows.split('/') }

    fun draw(graphics: GuiGraphicsExtractor, name: String, x: Int, y: Int, color: Int) {
        val rows = patterns.getValue(name)
        rows.forEachIndexed { dy, row ->
            row.forEachIndexed { dx, pixel ->
                if (pixel == '#') graphics.fill(x + dx, y + dy, x + dx + 1, y + dy + 1, color)
            }
        }
    }
}
